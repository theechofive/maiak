// Package secretsbootstrap implements `maiakctl secrets bootstrap` (ADR-0091): it creates the
// Kubernetes Secrets holding the admin login and the encryption keys when they are absent.
//
// It never overwrites anything. A complete Secret is left untouched; an incomplete one is an
// error, because guessing which half is right could lock the owner out or orphan encrypted data.
// Secrets are created with create-if-absent semantics; a 409 from a concurrent run is resolved by
// re-reading what the winner stored.
//
// Admin: the login is a system user (default `admin`, like Grafana). A random password is stored
// in plaintext in the initial Secret (read once by the owner,
// then deleted, like argocd-initial-admin-secret) and its argon2id hash in the admin Secret that
// the api consumes. The initial Secret is always created first, so the password the owner can
// read always matches the hash. If the admin Secret exists and the initial one is gone, the owner
// deleted it after logging in: nothing is recreated.
//
// Crypto: one 32-byte key in the formats config.LoadAPI parses (MAIAK_ENCRYPTION_KEYS and
// MAIAK_ENCRYPTION_ACTIVE_KEY_ID).
//
// Only Secret names and key names are logged, never values.
package secretsbootstrap

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"slices"
	"strings"

	"github.com/theechofive/maiak/backend/internal/dbbootstrap"
	"github.com/theechofive/maiak/backend/internal/platform/config"
	"github.com/theechofive/maiak/backend/internal/platform/crypto"
)

// Secret keys. The admin and crypto keys are what the chart maps to MAIAK_ADMIN_* and
// MAIAK_ENCRYPTION_* through secretKeyRef. Both admin Secrets store the login under KeyLogin.
const (
	KeyLogin        = "login"
	KeyPasswordHash = "password_hash"
	KeyPassword     = "password"
	KeyKeys         = "keys"
	KeyActiveKeyID  = "active_key_id"
)

// NoticeAnnotation is set on the initial admin Secret.
const NoticeAnnotation = "maiak/notice"

const notice = "One-time initial admin password generated by maiakctl secrets bootstrap. " +
	"Read it once, log in, then delete this Secret. Deleting it does not change the password."

// SecretStore is the part of the in-cluster Secret client (dbbootstrap.KubeSecrets) this
// package needs. CreateAnnotated returns dbbootstrap.ErrSecretExists when the name is taken.
type SecretStore interface {
	Get(ctx context.Context, namespace, name string) (data map[string][]byte, found bool, err error)
	CreateAnnotated(ctx context.Context, namespace, name string, data map[string][]byte, annotations map[string]string) error
}

// Options configure a run. AdminMode and CryptoMode are ModeGenerate or ModeSkip.
type Options struct {
	Namespace              string
	AdminMode              string
	CryptoMode             string
	AdminLogin             string
	AdminSecretName        string
	AdminInitialSecretName string
	CryptoSecretName       string
	CryptoKeyID            string
	Secrets                SecretStore
	Logger                 *slog.Logger
	// Rand defaults to crypto/rand.Reader.
	Rand io.Reader

	// hashParams defaults to crypto.DefaultArgon2Params (the `maiakctl hashpw` default); tests
	// lower it to keep the race detector fast.
	hashParams *crypto.Argon2Params
}

// Result reports what a run created.
type Result struct {
	AdminCreated        bool
	AdminInitialCreated bool
	CryptoCreated       bool
}

// maxAttempts bounds the re-read loop after losing a create race.
const maxAttempts = 3

// Run creates the Secrets that are absent.
func Run(ctx context.Context, o Options) (Result, error) {
	var res Result
	if o.Rand == nil {
		o.Rand = rand.Reader
	}
	if o.Logger == nil {
		o.Logger = slog.New(slog.DiscardHandler)
	}
	if o.Secrets == nil || o.Namespace == "" {
		return res, errors.New("secretsbootstrap: Secrets and Namespace are required")
	}
	if err := checkMode(o.AdminMode); err != nil {
		return res, err
	}
	if err := checkMode(o.CryptoMode); err != nil {
		return res, err
	}

	if o.CryptoMode == ModeGenerate {
		if err := o.ensureCrypto(ctx, &res); err != nil {
			return res, err
		}
	} else {
		o.Logger.Info("crypto secret skipped (mode skip)", "secret", o.CryptoSecretName)
	}
	if o.AdminMode == ModeGenerate {
		login, err := config.NormalizeLogin(o.AdminLogin)
		if err != nil {
			return res, fmt.Errorf("secretsbootstrap: %w", err)
		}
		o.AdminLogin = login
		if err := o.ensureAdmin(ctx, &res); err != nil {
			return res, err
		}
	} else {
		o.Logger.Info("admin secret skipped (mode skip)", "secret", o.AdminSecretName)
	}
	return res, nil
}

func checkMode(m string) error {
	if m != ModeGenerate && m != ModeSkip {
		return fmt.Errorf("secretsbootstrap: mode %q must be %s or %s", m, ModeGenerate, ModeSkip)
	}
	return nil
}

func (o *Options) ensureCrypto(ctx context.Context, res *Result) error {
	name := o.CryptoSecretName
	for range maxAttempts {
		data, found, err := o.Secrets.Get(ctx, o.Namespace, name)
		if err != nil {
			return err
		}
		if found {
			if err := complete(name, data, KeyKeys, KeyActiveKeyID); err != nil {
				return err
			}
			o.Logger.Info("secret exists, left untouched", "secret", name, "keys", sortedKeys(data))
			return nil
		}
		key := make([]byte, 32)
		if _, err := io.ReadFull(o.Rand, key); err != nil {
			return fmt.Errorf("secretsbootstrap: random key: %w", err)
		}
		keys, err := json.Marshal(map[string]string{o.CryptoKeyID: base64.StdEncoding.EncodeToString(key)})
		if err != nil {
			return err
		}
		err = o.Secrets.CreateAnnotated(ctx, o.Namespace, name, map[string][]byte{
			KeyKeys:        keys,
			KeyActiveKeyID: []byte(o.CryptoKeyID),
		}, nil)
		if errors.Is(err, dbbootstrap.ErrSecretExists) {
			continue // a concurrent run won; validate what it stored
		}
		if err != nil {
			return err
		}
		res.CryptoCreated = true
		o.Logger.Info("secret created", "secret", name, "keys", []string{KeyActiveKeyID, KeyKeys}, "key_id", o.CryptoKeyID)
		return nil
	}
	return fmt.Errorf("secretsbootstrap: secret %s/%s keeps changing; giving up", o.Namespace, name)
}

func (o *Options) ensureAdmin(ctx context.Context, res *Result) error {
	for range maxAttempts {
		done, err := o.adminOnce(ctx, res)
		if err != nil || done {
			return err
		}
	}
	return fmt.Errorf("secretsbootstrap: secrets %s/%s and %s keep changing; giving up", o.Namespace, o.AdminSecretName, o.AdminInitialSecretName)
}

// adminOnce returns done=false when a create lost a race and the caller should re-read.
func (o *Options) adminOnce(ctx context.Context, res *Result) (bool, error) {
	admin, initial := o.AdminSecretName, o.AdminInitialSecretName
	data, found, err := o.Secrets.Get(ctx, o.Namespace, admin)
	if err != nil {
		return false, err
	}
	if found {
		if err := complete(admin, data, KeyLogin, KeyPasswordHash); err != nil {
			return false, err
		}
		if !strings.EqualFold(string(data[KeyLogin]), o.AdminLogin) {
			o.Logger.Warn("admin secret login differs from the configured login; the existing secret wins (delete both admin secrets and re-sync to reset)",
				"secret", admin)
		}
		o.Logger.Info("secret exists, left untouched", "secret", admin, "keys", sortedKeys(data))
		return true, nil
	}

	var password string
	init, found, err := o.Secrets.Get(ctx, o.Namespace, initial)
	if err != nil {
		return false, err
	}
	if found {
		// A previous run stopped between the two creates: finish it with the stored password.
		if err := complete(initial, init, KeyLogin, KeyPassword); err != nil {
			return false, err
		}
		if !strings.EqualFold(string(init[KeyLogin]), o.AdminLogin) {
			return false, fmt.Errorf("secretsbootstrap: secret %s/%s holds a different login than the configured one and %s does not exist; delete %s and re-run",
				o.Namespace, initial, admin, initial)
		}
		password = string(init[KeyPassword])
		o.Logger.Info("initial admin secret exists without the admin secret; completing it", "secret", initial)
	} else {
		if password, err = o.newPassword(); err != nil {
			return false, err
		}
		err = o.Secrets.CreateAnnotated(ctx, o.Namespace, initial, map[string][]byte{
			KeyLogin:    []byte(o.AdminLogin),
			KeyPassword: []byte(password),
		}, map[string]string{NoticeAnnotation: notice})
		if errors.Is(err, dbbootstrap.ErrSecretExists) {
			return false, nil
		}
		if err != nil {
			return false, err
		}
		res.AdminInitialCreated = true
		o.Logger.Info("secret created", "secret", initial, "keys", []string{KeyLogin, KeyPassword})
	}

	params := crypto.DefaultArgon2Params
	if o.hashParams != nil {
		params = *o.hashParams
	}
	hash, err := crypto.HashPassword(password, params)
	if err != nil {
		return false, err
	}
	err = o.Secrets.CreateAnnotated(ctx, o.Namespace, admin, map[string][]byte{
		KeyLogin:        []byte(o.AdminLogin),
		KeyPasswordHash: []byte(hash),
	}, nil)
	if errors.Is(err, dbbootstrap.ErrSecretExists) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	res.AdminCreated = true
	o.Logger.Info("secret created", "secret", admin, "keys", []string{KeyLogin, KeyPasswordHash})
	return true, nil
}

// newPassword returns 24 random bytes as unpadded base64url (32 characters).
func (o *Options) newPassword() (string, error) {
	b := make([]byte, 24)
	if _, err := io.ReadFull(o.Rand, b); err != nil {
		return "", fmt.Errorf("secretsbootstrap: random password: %w", err)
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

// complete fails when an existing Secret lacks a required key or has it empty.
func complete(name string, data map[string][]byte, keys ...string) error {
	var missing []string
	for _, k := range keys {
		if len(data[k]) == 0 {
			missing = append(missing, k)
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("secretsbootstrap: secret %s exists but lacks key(s) %s (has %s); refusing to guess: fix it or delete it and re-sync",
			name, strings.Join(missing, ", "), strings.Join(sortedKeys(data), ", "))
	}
	return nil
}

func sortedKeys(data map[string][]byte) []string {
	keys := make([]string, 0, len(data))
	for k := range data {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
