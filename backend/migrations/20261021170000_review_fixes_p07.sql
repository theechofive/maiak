-- Creates a tenant and returns its id, or NULL when the slug is taken. The plan is decided here,
-- not by the caller: internal for the default tenant, free for every other one, so the api role
-- cannot create a tenant on a bigger plan. The id is a UUIDv7 generated by the app.
-- +goose StatementBegin
CREATE FUNCTION auth_create_tenant(p_id uuid, p_slug text, p_name text)
RETURNS uuid
LANGUAGE sql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    INSERT INTO tenants (id, slug, name, plan_key)
    VALUES (p_id, p_slug, p_name, CASE WHEN p_slug = 'default' THEN 'internal' ELSE 'free' END)
    ON CONFLICT (slug) DO NOTHING
    RETURNING id
$$;
-- +goose StatementEnd
REVOKE ALL ON FUNCTION auth_create_tenant(uuid, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION auth_create_tenant(uuid, text, text) TO maiak_api;

-- The number of the user's memberships in tenants other than p_tenant_id, deleted tenants
-- included. BootstrapAdmin refuses to adopt an existing user as the admin of the default tenant
-- when this is not zero (a stranger who registered the configured email). Reads memberships
-- through owner_membership_lookup.
-- +goose StatementBegin
CREATE FUNCTION auth_count_other_memberships(p_user_id uuid, p_tenant_id uuid)
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT count(*)::integer
    FROM memberships AS m
    WHERE m.user_id = p_user_id AND m.tenant_id <> p_tenant_id
$$;
-- +goose StatementEnd
REVOKE ALL ON FUNCTION auth_count_other_memberships(uuid, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION auth_count_other_memberships(uuid, uuid) TO maiak_api;

-- Deletes every session of the user in every tenant and returns how many. No new policy: the
-- sessions are found through owner_session_lookup and deleted tenant by tenant under the normal
-- tenant isolation policy. The caller's app.tenant_id is restored before returning (a function
-- SET clause cannot name a custom setting without superuser), so it does not leak into the
-- caller's transaction.
-- +goose StatementBegin
CREATE FUNCTION auth_revoke_user_sessions(p_user_id uuid)
RETURNS integer
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    caller text := current_setting('app.tenant_id', true);
    t      uuid;
    n      integer;
    total  integer := 0;
BEGIN
    FOR t IN SELECT DISTINCT s.tenant_id FROM sessions AS s WHERE s.user_id = p_user_id LOOP
        PERFORM set_config('app.tenant_id', t::text, true);
        DELETE FROM sessions AS s WHERE s.tenant_id = t AND s.user_id = p_user_id;
        GET DIAGNOSTICS n = ROW_COUNT;
        total := total + n;
    END LOOP;
    PERFORM set_config('app.tenant_id', COALESCE(caller, ''), true);
    RETURN total;
END
$$;
-- +goose StatementEnd
REVOKE ALL ON FUNCTION auth_revoke_user_sessions(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION auth_revoke_user_sessions(uuid) TO maiak_api;

-- Same signature, new body: a member of the default tenant always logs in there (the configured
-- admin cannot be steered into another tenant by an older membership); everybody else gets the
-- oldest membership as before (L-190).
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION auth_login_tenant(p_user_id uuid)
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT m.tenant_id
    FROM memberships AS m
    JOIN tenants AS t ON t.id = m.tenant_id
    WHERE m.user_id = p_user_id
      AND t.deleted_at IS NULL
    ORDER BY (t.slug = 'default') DESC, m.created_at, m.tenant_id
    LIMIT 1
$$;
-- +goose StatementEnd
